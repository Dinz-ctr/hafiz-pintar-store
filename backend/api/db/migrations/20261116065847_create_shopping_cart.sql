CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL
        REFERENCES customers(id) ON DELETE CASCADE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_carts_customer UNIQUE (customer_id)
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cart_id BIGINT NOT NULL
        REFERENCES carts(id) ON DELETE CASCADE,

    product_id BIGINT NOT NULL,
    variant_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL DEFAULT 1
        CHECK (quantity > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_cart_items_variant_product
        FOREIGN KEY (variant_id, product_id)
        REFERENCES product_variants(id, product_id)
        ON DELETE CASCADE,

    CONSTRAINT uq_cart_items_variant
        UNIQUE (cart_id, variant_id)
);

CREATE INDEX idx_cart_items_cart
    ON cart_items(cart_id);

CREATE INDEX idx_cart_items_product_variant
    ON cart_items(product_id, variant_id);


